public class Opexercise2 {
    public static void main(String[] args) {
       double a = 10.5;
       double b = 20.5;

       double hasilTambah = a + b;
       double hasilKurang = a - b;
       double hasilKali = a * b;
       double hasilBagi = a / b;
       double hasilSisaBagi = a % b;

       System.out.println("Hasil Penambahan : ");
       System.out.println(hasilTambah);
       System.out.println("Hasil Pengurangan : ");
       System.out.println(hasilKurang);
       System.out.println("Hasil Perkalian : ");
       System.out.println(hasilKali);
       System.out.println("Hasil Pembagian : ");
       System.out.println(hasilBagi);
       System.out.println("Hasil Sisa Pembagian : ");
       System.out.println(hasilSisaBagi);
    }
}
